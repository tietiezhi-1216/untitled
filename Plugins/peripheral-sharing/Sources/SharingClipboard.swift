import AppKit

@MainActor protocol SharingPasteboard: AnyObject {
    var changeCount: Int { get }
    var accessDenied: Bool { get }
    func readText() -> Data?
    func replaceText(_ text: String, ifUnchanged count: Int) -> Int?
    func replacePNG(_ data: Data, ifUnchanged count: Int) -> Int?
}

/// Read only the explicit plain-text representation, never coerce a file,
/// image or arbitrary object into text. No access to the board at construction.
@MainActor final class SharingSystemPasteboard: SharingPasteboard {
    private let pasteboard: () -> NSPasteboard
    private static let received = NSPasteboard.PasteboardType("com.untitled.app.peripheral-sharing.received-text")
    private static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private static let excludedTypes: Set<NSPasteboard.PasteboardType> = [received, concealed, .fileURL,
        .init("org.nspasteboard.TransientType"), .init("org.nspasteboard.AutoGeneratedType"),
        .init("de.petermaurer.TransientPasteboardType"), .init("com.agilebits.onepassword"),
        .init("com.typeit4me.clipping"), .init("Pasteboard generator type"),
        .init("NSFilenamesPboardType"), .init("NSFilesPromisePboardType"),
        .init("com.apple.pasteboard.promised-file-url"), .init("com.apple.pasteboard.promised-file-content-type")]

    init(pasteboard: @escaping () -> NSPasteboard = { .general }) { self.pasteboard = pasteboard }
    var changeCount: Int { pasteboard().changeCount }
    var accessDenied: Bool {
        if #available(macOS 15.4, *) { return pasteboard().accessBehavior == .alwaysDeny }
        return false
    }
    func readText() -> Data? {
        let board = pasteboard(), count = board.changeCount
        // Inspect metadata before asking any provider to materialize its data.
        guard let types = board.types, types.contains(.string), Self.excludedTypes.isDisjoint(with: types),
              let items = board.pasteboardItems, items.count == 1, let item = items.first,
              item.types.contains(.string), Self.excludedTypes.isDisjoint(with: item.types),
              let text = item.string(forType: .string), board.changeCount == count else { return nil }
        let bytes = text.utf8.prefix(SharingClipboardText.maximumBytes + 1)
        guard !bytes.isEmpty, bytes.count <= SharingClipboardText.maximumBytes else { return nil }
        return Data(bytes)
    }
    func replaceText(_ text: String, ifUnchanged count: Int) -> Int? {
        let item = NSPasteboardItem()
        guard item.setString(text, forType: .string) else { return nil }
        return Self.write(item, markedAs: Self.received, to: pasteboard(), expecting: count)
    }
    func replacePNG(_ data: Data, ifUnchanged count: Int) -> Int? {
        let item = NSPasteboardItem()
        guard item.setData(data, forType: .png) else { return nil }
        return Self.write(item, markedAs: Self.received, to: pasteboard(), expecting: count)
    }
    static func copyPairingCode(_ code: String) -> Int? {
        let item = NSPasteboardItem()
        guard item.setString(code, forType: .string) else { return nil }
        return write(item, markedAs: concealed, to: .general)
    }
    private static func write(_ item: NSPasteboardItem, markedAs type: NSPasteboard.PasteboardType,
                              to board: NSPasteboard, expecting count: Int? = nil) -> Int? {
        guard item.setData(Data(), forType: type), count == nil || board.changeCount == count else { return nil }
        let claim = board.prepareForNewContents(with: .currentHostOnly)
        guard board.changeCount == claim, board.writeObjects([item]) else { return nil }
        let written = board.changeCount
        guard board.types?.contains(type) == true, board.changeCount == written else { return nil }
        return written
    }
}

/// Grants and change counts live only in memory for the current authenticated
/// sharing session. No separate settings, initial snapshot, or offline queue.
@MainActor final class SharingClipboard {
    enum Status: String, Equatable {
        case disconnected, unsupported, paused, waiting, active, denied
    }

    private let board: any SharingPasteboard
    private let automatic: Bool
    private var timer: Timer?
    private var localGrant: UUID?
    private var peerGrant: UUID?
    private var observed: Int?
    private var reading = false
    private var supportsClipboard = false
    private var supportsImages = false
    private var sentRevision: UInt64 = 0, receivedRevision: UInt64 = 0
    private(set) var status: Status = .disconnected
    var changed: (Status) -> Void = { _ in }
    var isAuthorized: () -> Bool = { false }
    var canSendText: () -> Bool = { false }
    var send: (SharingMessage) -> Bool = { _ in false }
    var configureImages: (SharingClipboardGrants?) -> Void = { _ in }
    var sendImage: (Data, UInt64) -> Void = { _, _ in }
    var discardPendingImage: () -> Void = {}

    init(board: any SharingPasteboard = SharingSystemPasteboard(), automatic: Bool = true) {
        self.board = board; self.automatic = automatic
    }
    isolated deinit { timer?.invalidate() }

    func connect(supported: Bool, images: Bool = false) {
        clearConsent()
        supportsClipboard = supported; supportsImages = supported && images
        if supported { refreshAuthorization() } else { publish(.unsupported) }
    }
    func disconnect() {
        clearConsent()
        supportsClipboard = false; supportsImages = false
        publish(.disconnected)
    }
    /// Share follows the host's existing session, not a clipboard preference.
    /// The wire grant still limits both directions to this live connection.
    func refreshAuthorization() {
        guard supportsClipboard else { return }
        guard isAuthorized() else { suspend(as: .paused); return }
        if localGrant != nil {
            // Active sessions already check denial on their sampling tick.
            if status == .waiting && board.accessDenied { denyAccess() }
            return
        }
        guard !board.accessDenied else { publish(.denied); return }
        let grant = UUID()
        localGrant = grant
        guard send(.init(kind: .clipboardConsent, enabled: true, clipboardGrant: grant)) else {
            guard localGrant == grant else { return } // Sending can synchronously disconnect.
            localGrant = nil; publish(.paused)
            return
        }
        updateSampling()
    }
    func acceptConsent(_ message: SharingMessage) {
        guard supportsClipboard, message.kind == .clipboardConsent,
              let enabled = message.enabled, enabled == (message.clipboardGrant != nil),
              peerGrant != message.clipboardGrant else { return }
        // Remember the peer's grant even if local sharing is paused. It is
        // never permission to read/write without our own active grant.
        peerGrant = message.clipboardGrant
        if localGrant != nil { updateSampling() }
    }
    func acceptText(_ value: SharingClipboardText) {
        guard status == .active, isAuthorized(), localGrant == value.to, peerGrant == value.from,
              let text = value.text, acceptRevision(value.revision) else { return }
        guard !board.accessDenied else { denyAccess(); return }
        // A local copy waiting to be sampled takes precedence over incoming
        // text. Do not read its contents or overwrite it here.
        guard let observed, board.changeCount == observed else { return }
        if let count = board.replaceText(text, ifUnchanged: observed), status == .active,
           localGrant == value.to, peerGrant == value.from {
            self.observed = count // Receiving does not generate a send.
        }
    }
    func offerCopiedPNG(_ data: Data, changeCount: Int) {
        guard supportsImages, status == .active, isAuthorized() else { return }
        // Never fetch image bytes from the system pasteboard. Capture already
        // has the final PNG and has completed its local clipboard write.
        guard !board.accessDenied else { denyAccess(); return }
        guard board.changeCount == changeCount else { return }
        observed = changeCount
        discardPendingImage()
        guard SharingClipboardImageHeader.fitsPNG(data) else { return }
        sendImage(data, nextRevision())
    }
    func beginImage(revision: UInt64) -> SharingClipboardImageLink.Delivery? {
        guard supportsImages, status == .active, isAuthorized(), let localGrant, let peerGrant,
              acceptRevision(revision) else { return nil }
        guard !board.accessDenied else { denyAccess(); return nil }
        guard let observed, board.changeCount == observed else { return nil }
        return { [weak self] png in
            guard let self, self.status == .active, self.isAuthorized(), self.localGrant == localGrant,
                  self.peerGrant == peerGrant, self.receivedRevision == revision, self.observed == observed else { return }
            guard !self.board.accessDenied else { self.denyAccess(); return }
            if let count = self.board.replacePNG(png, ifUnchanged: observed) { self.observed = count }
        }
    }
    private func acceptRevision(_ revision: UInt64?) -> Bool {
        guard supportsImages else { return revision == nil }
        guard let revision, revision > receivedRevision else { return false }
        receivedRevision = revision
        return true
    }
    private func nextRevision() -> UInt64 { sentRevision &+= 1; return sentRevision }

    func sample() {
        guard !reading, status == .active, let localGrant, let peerGrant, let observed, isAuthorized() else { return }
        guard !board.accessDenied else { denyAccess(); return }
        let current = board.changeCount
        guard current != observed else { return }
        discardPendingImage()
        guard canSendText() else { return }
        reading = true
        defer { reading = false }
        let bytes = board.readText()
        // A read may materialize promised data from another app. Do not send
        // that result after a switch/stop or if the pasteboard changed meanwhile.
        guard board.changeCount == current, isAuthorized(), status == .active,
              self.localGrant == localGrant, self.peerGrant == peerGrant else { return }
        guard !board.accessDenied else { denyAccess(); return }
        self.observed = current
        guard let bytes else { return }
        let value = SharingClipboardText(from: localGrant, to: peerGrant, utf8: bytes,
                                         revision: supportsImages ? nextRevision() : nil)
        guard value.text != nil else { return }
        _ = send(.init(kind: .clipboardText, clipboardText: value))
    }
    private func updateSampling() {
        stopSampling()
        guard supportsClipboard, isAuthorized(), let localGrant else { return }
        guard let peerGrant else { publish(.waiting); return }
        guard !board.accessDenied else { denyAccess(); return }
        observed = board.changeCount // Start with metadata only; do not send the current contents.
        if supportsImages { configureImages(.init(local: localGrant, peer: peerGrant)) }
        if automatic {
            let timer = Timer(timeInterval: 0.1, repeats: true) { [weak self] _ in
                MainActor.assumeIsolated { self?.sample() }
            }
            timer.tolerance = 0.02
            self.timer = timer
            RunLoop.main.add(timer, forMode: .common)
        }
        publish(.active)
    }
    private func denyAccess() { suspend(as: .denied) }
    private func suspend(as state: Status) {
        let hadGrant = localGrant != nil
        guard hadGrant || status != state else { return }
        localGrant = nil; stopSampling(); publish(state)
        if hadGrant { _ = send(.init(kind: .clipboardConsent, enabled: false)) }
    }
    private func stopSampling() {
        timer?.invalidate(); timer = nil; observed = nil
        sentRevision = 0; receivedRevision = 0
        if supportsImages { configureImages(nil) }
    }
    private func clearConsent() {
        stopSampling(); localGrant = nil; peerGrant = nil
    }
    private func publish(_ value: Status) {
        guard status != value else { return }
        status = value; changed(value)
    }
}
