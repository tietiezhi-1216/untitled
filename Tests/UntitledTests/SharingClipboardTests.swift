    @Test func textFrameLimitsAndConsentShape() throws {
        let sender = UUID(), receiver = UUID()
        let text = String(repeating: "🐾", count: SharingClipboardText.maximumBytes / 4)
        let valid = SharingClipboardText(from: sender, to: receiver, utf8: Data(text.utf8))
        let frame = try SharingFramer.encode(.init(kind: .clipboardText, clipboardText: valid))
        #expect(frame.count < 45 * 1024)
        var framer = SharingFramer()
        #expect(try framer.append(frame.prefix(5)).isEmpty)
        #expect(try framer.append(frame.dropFirst(5)).first?.clipboardText == valid)
        for bytes in [Data(), Data([0xFF]), Data(repeating: 0x61, count: SharingClipboardText.maximumBytes + 1)] {
            let value = SharingClipboardText(from: sender, to: receiver, utf8: bytes)
            #expect(throws: PluginError.self) { try SharingFramer.encode(.init(kind: .clipboardText, clipboardText: value)) }
        }
        for invalid in [SharingMessage(kind: .clipboardConsent, enabled: true),
                        .init(kind: .clipboardConsent, enabled: false, clipboardGrant: sender),
                        .init(kind: .ping, clipboardSync: true), .init(kind: .ping, clipboardGrant: sender),
                        .init(kind: .ping, clipboardText: valid), .init(kind: .clipboardText)] {
            #expect(throws: PluginError.self) { try invalid.validate() }
        }
        try SharingMessage(kind: .clipboardConsent, enabled: true, clipboardGrant: sender).validate()
        try SharingMessage(kind: .clipboardConsent, enabled: false).validate()
    }

    @Test func nativeAdapterOnlyReadsUnmarkedPlainTextOnAPrivateBoard() throws {
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        let adapter = SharingSystemPasteboard(pasteboard: { board })
        func put(_ text: String, extra: NSPasteboard.PasteboardType? = nil) {
            let item = NSPasteboardItem()
            #expect(item.setString(text, forType: .string))
            if let extra { #expect(item.setData(Data(), forType: extra)) }
            board.clearContents(); #expect(board.writeObjects([item]))
        }
        let text = "这是一段文本\nالعربية🐾"
        put(text)
        #expect(adapter.readText() == Data(text.utf8))
        for type in [NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
                     .init("org.nspasteboard.AutoGeneratedType"), .init("com.agilebits.onepassword"), .fileURL,
                     .init("com.apple.pasteboard.promised-file-url")] {
            put(text, extra: type)
            #expect(adapter.readText() == nil)
        }
        put(String(repeating: "汉", count: 11_000))
        #expect(adapter.readText() == nil) // Byte cap, not Character count.
        let old = board.changeCount
        put(text)
        #expect(adapter.replaceText("stale", ifUnchanged: old) == nil)
        #expect(board.string(forType: .string) == text)
        let installed = try #require(adapter.replaceText("remote 🐾", ifUnchanged: board.changeCount))
        #expect(board.changeCount == installed && board.string(forType: .string) == "remote 🐾")
        #expect(adapter.readText() == nil) // Received marker also guards a later sampler.
    }

