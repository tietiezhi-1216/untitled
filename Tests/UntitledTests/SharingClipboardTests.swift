        let b = makeController(defaults: db, key: key, clipboard: cb)
        defer { a.stop(); b.stop(); da.removePersistentDomain(forName: one); db.removePersistentDomain(forName: two) }
        try a.startUserSession(localOnly: true); try b.startUserSession(localOnly: true)
        try await wait { a.transport.port != nil && b.transport.port != nil }
        let port = try #require(b.transport.port).rawValue
        try a.connect(host: "127.0.0.1", port: String(port))
        try await wait { a.layoutReady && b.layoutReady && a.clipboardImageStatus == .ready && b.clipboardImageStatus == .ready }
        let stamp = a.layoutStamp
        pa.copy("before loss"); ca.sample()
        try await wait { pb.text == "before loss" }

        // Close the listener and socket together, not the user's sharing switch.
        // Also exercise a refused dial: a restarted listener won't change the
        // network path that a waiting NWConnection would otherwise await.
        var refused = false
        a.transport.diagnostics = { if $0.contains("waiting") || $0.contains("failed") { refused = true } }
        b.stop()
        try await wait { refused && a.reconnecting && a.transport.canDial && a.clipboardStatus == .disconnected }
        #expect(a.isRunning && a.keyboardMouseEnabled && a.clipboardImageStatus == .inactive)
        pa.copy("while offline"); ca.sample()
        try b.start(key: key, localOnly: true, listenPort: port)
        try b.restoreUserSessionIfRequested(localOnly: true)
        try await wait { !a.reconnecting && a.layoutReady && b.layoutReady && a.clipboardImageStatus == .ready && b.clipboardImageStatus == .ready }
        #expect(a.layoutStamp == stamp && a.control == .local && b.control == .local)
        #expect(a.sentInputPackets == 0 && b.receivedInputPackets == 0)
        ca.sample(); cb.sample()
        #expect(pa.text == "while offline" && pb.text == "before loss" && pb.writes == 1)
        pa.copy("after reconnect"); ca.sample()
        try await wait { pb.text == "after reconnect" }
    }

