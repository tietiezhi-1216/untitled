        return controller
    }

    private func testPNG(width: Int = 64, height: Int = 64) throws -> Data {
        // Deterministic high-entropy RGB pixels, no capture of the user's screen.
        var seed: UInt32 = 11173
        var pixels = Data(count: width * height * 4)
        pixels.withUnsafeMutableBytes { bytes in
            for index in 0..<bytes.count {
                seed = seed &* 1664525 &+ 1013904223
                bytes[index] = index % 4 == 3 ? 255 : UInt8(truncatingIfNeeded: seed >> 24)
            }
        }
        let provider = try #require(CGDataProvider(data: pixels as CFData))
        let image = try #require(CGImage(width: width, height: height, bitsPerComponent: 8, bitsPerPixel: 32,
            bytesPerRow: width * 4, space: CGColorSpaceCreateDeviceRGB(),
            bitmapInfo: CGBitmapInfo(rawValue: CGImageAlphaInfo.noneSkipLast.rawValue), provider: provider,
            decode: nil, shouldInterpolate: false, intent: .defaultIntent))
        return try CaptureImage.png(image)
    }

    private func wait(sourceLocation: SourceLocation = #_sourceLocation, _ condition: () -> Bool) async throws {
        for _ in 0..<500 {
            if condition() { return }
            try await Task.sleep(for: .milliseconds(5))
        }
        try #require(condition(), sourceLocation: sourceLocation)
    }
